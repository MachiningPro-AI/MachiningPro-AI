# ---------------------------------------------------------------------------
# Tool lookup helpers
# ---------------------------------------------------------------------------

_lib = ToolLibrary()


def _find_drill(diameter_mm: float | None) -> tuple[ToolInfo, str | None]:
    """Return best-match drill from catalog; status=INSUFFICIENT_DATA if none found."""
    if diameter_mm is None or diameter_mm <= 0:
        return ToolInfo(tool_status="INSUFFICIENT_DATA"), None
    q = _lib.query().by_family(ToolFamily.DRILLING)
    if diameter_mm:
        tol = max(0.5, diameter_mm * 0.1)
        q = q.by_diameter(min_mm=diameter_mm - tol, max_mm=diameter_mm + tol)
    results = q.results()
    if not results:
        # Try any drill
        results = _lib.query().by_family(ToolFamily.DRILLING).results()
    if not results:
        return ToolInfo(tool_status="INSUFFICIENT_DATA"), None
    tool = results[0]
    info = ToolInfo(
        tool_id=tool.stable_id,
        tool_type=tool.tool_category_code or "DRILL",
        tool_diameter_mm=tool.cutting_diameter_mm,
        cutting_length_mm=tool.cutting_length_mm,
        overall_length_mm=tool.overall_length_mm,
        tool_provenance="CATALOG",
        tool_status="CATALOG_MATCH",
    )
    return info, tool.stable_id


def _find_end_mill(diameter_mm: float | None) -> tuple[ToolInfo, str | None]:
    """Return best-match end mill from catalog."""
    q = _lib.query().by_family(ToolFamily.MILLING)
    results = q.results()
    if not results:
        return ToolInfo(tool_status="INSUFFICIENT_DATA"), None
    # Prefer end mills; pick closest diameter if known
    end_mills = [r for r in results if (r.tool_category_code or "").upper() == "END_MILL"]
    pool = end_mills if end_mills else results
    if diameter_mm:
        pool_sorted = sorted(
            pool,
            key=lambda r: abs((r.cutting_diameter_mm or 999) - diameter_mm)
        )
        tool = pool_sorted[0]
    else:
        tool = pool[0]
    info = ToolInfo(
        tool_id=tool.stable_id,
        tool_type=tool.tool_category_code or "END_MILL",
        tool_diameter_mm=tool.cutting_diameter_mm,
        cutting_length_mm=tool.cutting_length_mm,
        overall_length_mm=tool.overall_length_mm,
        tool_provenance="CATALOG",
        tool_status="CATALOG_MATCH",
    )
    return info, tool.stable_id


# ---------------------------------------------------------------------------
# Segment → ToolpathGroupFE converters
# ---------------------------------------------------------------------------

_FEED_TYPES = {
    MotionType.CUT, MotionType.ENTRY, MotionType.EXIT,
    MotionType.RAMP, MotionType.HELIX, MotionType.ARC,
}
_RAPID_TYPES = {MotionType.RAPID, MotionType.APPROACH, MotionType.LINK}
_PLUNGE_TYPES = {MotionType.PLUNGE}
_RETRACT_TYPES = {MotionType.RETRACT}


def _motion_to_fe(mt: MotionType | str) -> str:
    s = str(mt)
    if s in {m.value for m in _RAPID_TYPES}:
        return "RAPID"
    if s in {m.value for m in _PLUNGE_TYPES}:
        return "PLUNGE"
    if s in {m.value for m in _RETRACT_TYPES}:
        return "RETRACT"
    return "FEED"


def _seg_points(seg: ToolpathSegment) -> list[float]:
    if seg.polyline_points and len(seg.polyline_points) >= 2:
        pts: list[float] = []
        for p in seg.polyline_points:
            pts.extend([p[0], p[1], p[2]])
        return pts
    if seg.start_point and seg.end_point:
        s, e = seg.start_point, seg.end_point
        return [s[0], s[1], s[2], e[0], e[1], e[2]]
    return []


def _tp_to_groups(tp: Toolpath, op_ref: str) -> list[ToolpathGroupFE]:
    groups: list[ToolpathGroupFE] = []
    for seg in tp.segments:
        pts = _seg_points(seg)
        if len(pts) < 6:
            continue
        groups.append(ToolpathGroupFE(
            motion_type=_motion_to_fe(seg.motion_type),
            points=pts,
            operation_ref=op_ref,
        ))
    return groups


def _count_segments(tp: Toolpath) -> dict[str, int]:
    rapid = feed = entry = retract = 0
    for seg in tp.segments:
        fe = _motion_to_fe(seg.motion_type)
        if fe == "RAPID":
            rapid += 1
        elif fe == "RETRACT":
            retract += 1
        elif fe == "FEED":
            feed += 1
        else:
            entry += 1
    total = len(tp.segments)
    pts = sum(2 if (s.start_point and s.end_point) else len(s.polyline_points) for s in tp.segments)
    return dict(total=total, rapid=rapid, feed=feed, entry=entry, retract=retract, pts=pts)


# ---------------------------------------------------------------------------
# Main endpoint
# ---------------------------------------------------------------------------

def _resolve_clearance(
    feat: FeatureCamFeatureInput,
    stock: StockBboxInput | None,
) -> tuple[float | None, ClearanceSource]:
    if feat.clearance_z is not None:
        return feat.clearance_z, ClearanceSource.USER_DEFINED
    if stock is not None:
        h = stock.max_z - stock.min_z
        return stock.max_z + max(h * 0.15, 5.0), ClearanceSource.BBOX_DERIVED
    return None, ClearanceSource.UNKNOWN


@router.post("/feature-cam", response_model=FeatureCamResult)
def feature_cam(
    req: FeatureCamRequest,
    authorization: str | None = Header(default=None),
) -> FeatureCamResult:
    """
    Generate real toolpaths from manufacturing features.

    Uses existing Level-10 generators (drill, pocket, slot).
    Does NOT fabricate tool geometry or clearance.
    Missing required input → operation status BLOCKED, never fabricated.
    """
    _require_user(authorization)

    operations: list[FeatureCamOperationResult] = []
    all_groups: list[ToolpathGroupFE] = []
    warnings: list[str] = []
    op_idx = 1

    for feat in req.features:
        op_ref = f"{req.operation_prefix}{op_idx:02d}_{feat.feature_type}_{feat.feature_id[:8]}"
        clearance_z, clearance_src = _resolve_clearance(feat, req.stock_bbox)
        ftype = feat.feature_type.upper()

        if ftype in ("HOLE", "DRILL"):
            tool_info, tool_ref = _find_drill(feat.diameter_mm)
            inp = DrillInput(
                operation_ref=op_ref,
                hole_x=feat.center_x if feat.center_x is not None else 0.0,
                hole_y=feat.center_y if feat.center_y is not None else 0.0,
                hole_top_z=feat.center_z_top if feat.center_z_top is not None else 0.0,
                hole_depth_mm=feat.depth_mm if feat.depth_mm is not None else 0.0,
                clearance_z=clearance_z,
                clearance_source=clearance_src,
                setup_ref=req.setup_ref,
                wcs_ref=req.wcs_ref,
                tool_ref=tool_ref,
                feature_refs=[feat.feature_id],
            )
            # Block on missing geometry
            missing: list[str] = []
            if feat.center_x is None or feat.center_y is None:
                missing.append("center_x, center_y")
            if feat.center_z_top is None:
                missing.append("center_z_top")
            if feat.depth_mm is None or feat.depth_mm <= 0:
                missing.append("depth_mm")
            if missing:
                operations.append(FeatureCamOperationResult(
                    operation_ref=op_ref,
                    operation_index=op_idx,
                    feature_id=feat.feature_id,
                    feature_type=feat.feature_type,
                    operation_type="DRILL",
                    cam_strategy="DRILL_CYCLE",
                    wcs_ref=req.wcs_ref,
                    tool=tool_info,
                    cutting_params=CuttingParamsInfo(),
                    toolpath_status="BLOCKED",
                    warnings=[f"MISSING_GEOMETRY: {', '.join(missing)}"],
                    missing_inputs=missing,
                ))
                op_idx += 1
                continue
            tp = generate_drill_toolpath(inp)
            groups = _tp_to_groups(tp, op_ref)
            all_groups.extend(groups)
            counts = _count_segments(tp)
            operations.append(FeatureCamOperationResult(
                operation_ref=op_ref,
                operation_index=op_idx,
                feature_id=feat.feature_id,
                feature_type=feat.feature_type,
                operation_type="DRILL",
                cam_strategy="DRILL_CYCLE",
                wcs_ref=req.wcs_ref,
                tool=tool_info,
                cutting_params=CuttingParamsInfo(),
                toolpath_status=tp.status.value if tp.status else "BLOCKED",
                toolpath_id=tp.toolpath_id,
                segment_count=counts["total"],
                rapid_segments=counts["rapid"],
                feed_segments=counts["feed"],
                entry_segments=counts["entry"],
                retract_segments=counts["retract"],
                point_count=counts["pts"],
                warnings=tp.warnings,
                missing_inputs=tp.missing_inputs,
            ))

        elif ftype in ("POCKET", "POCKET_MILLING"):
            tool_hint = feat.diameter_mm or (feat.width_mm / 3 if feat.width_mm else None)
            tool_info, tool_ref = _find_end_mill(tool_hint)
            tool_diam = tool_info.tool_diameter_mm

            # Build boundary from feature width/length or provided points
            if feat.boundary_points and len(feat.boundary_points) >= 3:
                boundary = [(p[0], p[1]) for p in feat.boundary_points]
            elif (feat.center_x is not None and feat.center_y is not None
                  and feat.width_mm and feat.length_mm):
                cx, cy = feat.center_x, feat.center_y
                hw, hl = feat.width_mm / 2, feat.length_mm / 2
                boundary = [
                    (cx - hw, cy - hl), (cx + hw, cy - hl),
                    (cx + hw, cy + hl), (cx - hw, cy + hl),
                ]
            else:
                boundary = None

            pocket_top = feat.center_z_top
            pocket_bottom = (
                (pocket_top - feat.depth_mm)
                if (pocket_top is not None and feat.depth_mm)
                else None
            )

            missing = []
            if boundary is None:
                missing.append("pocket_boundary_points or center+width+length")
            if pocket_top is None:
                missing.append("center_z_top")
            if feat.depth_mm is None or feat.depth_mm <= 0:
                missing.append("depth_mm")
            if tool_diam is None:
                missing.append("tool_diameter_mm (no catalog tool found)")

            if missing:
                operations.append(FeatureCamOperationResult(
                    operation_ref=op_ref,
                    operation_index=op_idx,
                    feature_id=feat.feature_id,
                    feature_type=feat.feature_type,
                    operation_type="POCKET_MILLING",
                    cam_strategy="OFFSET_POCKET",
                    wcs_ref=req.wcs_ref,
                    tool=tool_info,
                    cutting_params=CuttingParamsInfo(),
                    toolpath_status="BLOCKED",
                    warnings=[f"MISSING_GEOMETRY: {', '.join(missing)}"],
                    missing_inputs=missing,
                ))
                op_idx += 1
                continue

            assert boundary is not None
            assert pocket_top is not None
            assert pocket_bottom is not None
            assert tool_diam is not None

            # Use 30% of tool diameter as stepdown/stepover (conservative starting point)
            stepdown = round(tool_diam * 0.30, 3)
            stepover = round(tool_diam * 0.40, 3)

            inp_p = PocketInput(
                operation_ref=op_ref,
                boundary_points=boundary,
                pocket_top_z=pocket_top,
                pocket_bottom_z=pocket_bottom,
                tool_diameter_mm=tool_diam,
                stepdown_mm=stepdown,
                stepover_mm=stepover,
                clearance_z=clearance_z,
                clearance_source=clearance_src,
                setup_ref=req.setup_ref,
                wcs_ref=req.wcs_ref,
                tool_ref=tool_ref,
                feature_refs=[feat.feature_id],
            )
            tp = generate_pocket_toolpath(inp_p)
            groups = _tp_to_groups(tp, op_ref)
            all_groups.extend(groups)
            counts = _count_segments(tp)
            operations.append(FeatureCamOperationResult(
                operation_ref=op_ref,
                operation_index=op_idx,
                feature_id=feat.feature_id,
                feature_type=feat.feature_type,
                operation_type="POCKET_MILLING",
                cam_strategy="OFFSET_POCKET",
                wcs_ref=req.wcs_ref,
                tool=tool_info,
                cutting_params=CuttingParamsInfo(
                    doc_mm=stepdown,
                    woc_mm=stepover,
                    provenance="MANUFACTURER_START",
                    status="SUGGESTED",
                ),
                toolpath_status=tp.status.value if tp.status else "BLOCKED",
                toolpath_id=tp.toolpath_id,
                segment_count=counts["total"],
                rapid_segments=counts["rapid"],
                feed_segments=counts["feed"],
                entry_segments=counts["entry"],
                retract_segments=counts["retract"],
                point_count=counts["pts"],
                warnings=tp.warnings,
                missing_inputs=tp.missing_inputs,
            ))

        elif ftype in ("SLOT", "SLOT_MILLING"):
            tool_hint = feat.width_mm / 2 if feat.width_mm else feat.diameter_mm
            tool_info, tool_ref = _find_end_mill(tool_hint)
            tool_diam = tool_info.tool_diameter_mm

            missing = []
            if feat.center_x is None or feat.center_y is None:
                missing.append("center_x, center_y")
            if feat.center_z_top is None:
                missing.append("center_z_top")
            if feat.depth_mm is None:
                missing.append("depth_mm")
            if feat.width_mm is None:
                missing.append("slot_width_mm")
            if feat.length_mm is None:
                missing.append("slot_length_mm")

            if missing:
                operations.append(FeatureCamOperationResult(
                    operation_ref=op_ref,
                    operation_index=op_idx,
                    feature_id=feat.feature_id,
                    feature_type=feat.feature_type,
                    operation_type="SLOT_MILLING",
                    cam_strategy="SLOT_CENTERLINE",
                    wcs_ref=req.wcs_ref,
                    tool=tool_info,
                    cutting_params=CuttingParamsInfo(),
                    toolpath_status="BLOCKED",
                    warnings=[f"MISSING_GEOMETRY: {', '.join(missing)}"],
                    missing_inputs=missing,
                ))
                op_idx += 1
                continue

            assert feat.center_x is not None
            assert feat.center_y is not None
            assert feat.center_z_top is not None
            assert feat.length_mm is not None

            half_len = feat.length_mm / 2
            inp_s = SlotInput(
                operation_ref=op_ref,
                slot_start=(feat.center_x - half_len, feat.center_y),
                slot_end=(feat.center_x + half_len, feat.center_y),
                slot_z=feat.center_z_top,
                slot_width_mm=feat.width_mm,
                slot_depth_mm=feat.depth_mm,
                tool_diameter_mm=tool_diam,
                clearance_z=clearance_z,
                clearance_source=clearance_src,
                setup_ref=req.setup_ref,
                wcs_ref=req.wcs_ref,
                tool_ref=tool_ref,
                feature_refs=[feat.feature_id],
            )
            tp = generate_slot_toolpath(inp_s)
            groups = _tp_to_groups(tp, op_ref)
            all_groups.extend(groups)
            counts = _count_segments(tp)
            operations.append(FeatureCamOperationResult(
                operation_ref=op_ref,
                operation_index=op_idx,
                feature_id=feat.feature_id,
                feature_type=feat.feature_type,
                operation_type="SLOT_MILLING",
                cam_strategy="SLOT_CENTERLINE",
                wcs_ref=req.wcs_ref,
                tool=tool_info,
                cutting_params=CuttingParamsInfo(),
                toolpath_status=tp.status.value if tp.status else "BLOCKED",
                toolpath_id=tp.toolpath_id,
                segment_count=counts["total"],
                rapid_segments=counts["rapid"],
                feed_segments=counts["feed"],
                entry_segments=counts["entry"],
                retract_segments=counts["retract"],
                point_count=counts["pts"],
                warnings=tp.warnings,
                missing_inputs=tp.missing_inputs,
            ))

        else:
            # Unsupported feature type — BLOCKED, never fabricated
            operations.append(FeatureCamOperationResult(
                operation_ref=op_ref,
                operation_index=op_idx,
                feature_id=feat.feature_id,
                feature_type=feat.feature_type,
                operation_type="NOT_IMPLEMENTED",
                cam_strategy="NOT_IMPLEMENTED",
                wcs_ref=req.wcs_ref,
                tool=ToolInfo(tool_status="NOT_APPLICABLE"),
                cutting_params=CuttingParamsInfo(),
                toolpath_status="BLOCKED",
                warnings=[
                    f"FEATURE_TYPE_NOT_IMPLEMENTED: {feat.feature_type} — "
                    "supported: HOLE, POCKET, SLOT"
                ],
                missing_inputs=[f"feature_type_support: {feat.feature_type}"],
            ))

        op_idx += 1

    return FeatureCamResult(
        file_ref=req.file_ref,
        operations=operations,
        toolpath_groups=all_groups,
        warnings=warnings,
        safety=_SAFETY,
    )
