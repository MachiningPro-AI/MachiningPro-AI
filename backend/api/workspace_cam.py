class StockBboxInput(BaseModel):
    min_x: float
    min_y: float
    min_z: float
    max_x: float
    max_y: float
    max_z: float


class FeatureCamFeatureInput(BaseModel):
    feature_id: str
    feature_type: str  # HOLE, POCKET, SLOT, STEP_SHOULDER, PLANAR_FACE
    center_x: float | None = None
    center_y: float | None = None
    center_z_top: float | None = None
    depth_mm: float | None = None
    diameter_mm: float | None = None
    width_mm: float | None = None
    length_mm: float | None = None
    clearance_z: float | None = None
    # Pocket boundary points (optional)
    boundary_points: list[list[float]] | None = None


class FeatureCamRequest(BaseModel):
    file_ref: str
    features: list[FeatureCamFeatureInput] = Field(default_factory=list)
    stock_bbox: StockBboxInput | None = None
    material_grade: str | None = None
    operation_prefix: str = "OP"
    wcs_ref: str = "WCS_PART_ORIGIN"
    setup_ref: str = "SETUP_01"


