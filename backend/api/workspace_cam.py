"""
Workspace Feature-Aware CAM Endpoint.

POST /api/workspace-cam/feature-cam

Accepts a list of manufacturing features (HOLE, POCKET, SLOT, PLANAR_FACE, STEP_SHOULDER)
with geometry derived from prior CAD analysis, plus optional stock bbox and material,
and returns real toolpath segments generated by the existing Level-10 toolpath engine.

Safety contract:
  NO_FABRICATED_TOOLPATH=YES     — all segments from real generators
  NO_FABRICATED_TOOL=YES         — missing tool → INSUFFICIENT_DATA, never invented
  NO_FAKE_CLEARANCE=YES          — clearance from stock bbox or feature; MISSING if absent
  NO_CNC_DISPATCH=YES
  is_dispatchable=false
  production_released=false
  SIMULATION_REQUIRED=YES        — every operation declares simulation required
  HARD_RULE_11=YES               — missing input → NOT_VERIFIABLE / BLOCKED, never PASS
"""

from __future__ import annotations

from typing import Any

from fastapi import APIRouter, Header, HTTPException
from pydantic import BaseModel, Field

from backend.api.auth import verify_token
from backend.cutting_tools.families import ToolFamily
from backend.cutting_tools.library import ToolLibrary
from backend.toolpath.enums import ClearanceSource, MotionType
from backend.toolpath.generators import (
    DrillInput,
    PocketInput,
    SlotInput,
    generate_drill_toolpath,
    generate_pocket_toolpath,
    generate_slot_toolpath,
)
from backend.toolpath.models import Toolpath, ToolpathSegment

router = APIRouter(prefix="/api/workspace-cam", tags=["workspace-cam"])

_SAFETY = {
    "is_dispatchable": False,
    "production_released": False,
    "simulation_required": True,
    "no_cnc_dispatch": True,
    "no_auto_approve": True,
    "hard_rule_11": "MISSING_INPUT_NEVER_PASS",
}


def _require_user(authorization: str | None = Header(default=None)) -> dict[str, Any]:
    scheme, _, token = (authorization or "").partition(" ")
    payload = (
        verify_token(token.strip())
        if scheme.lower() == "bearer" and token.strip()
        else None
    )
    if payload is None:
        raise HTTPException(401, detail={"error_code": "UNAUTHENTICATED"})
    return payload


